-- ============================================
-- 4. Religa os resumos que ja cobrem um topico
-- ============================================

with melhor as (
  select distinct on (e.id) e.id as topico, r.id as resumo
    from edital_topicos e
    join resumos r
      on r.materia_slug = e.materia_slug
     and length(r.titulo) >= 5
     and (
       -- titulo de uma palavra so: o topico tem que SER ele. Sem isto,
       -- "Discurso" casava com doze topicos que so mencionam a palavra, e
       -- "Equilibrio" (o resumo de mecanica) caia em "equilibrio termico".
       (position(' ' in btrim(r.titulo)) = 0
          and lower(btrim(e.texto, ' .;:')) = lower(btrim(r.titulo)))
       or
       -- titulo de duas palavras ou mais: basta aparecer inteiro, entre
       -- fronteiras de palavra (\m e \M). Substring cru nao serve: "Dinamica"
       -- casa dentro de "termodinamica" e de "hidrodinamica".
       (position(' ' in btrim(r.titulo)) > 0
          and lower(e.texto) ~ ('\m' || lower(regexp_replace(r.titulo,'([().\[\]{}*+?^$|\\])','\\\1','g')) || '\M'))
     )
   order by e.id, length(r.titulo) desc
)
update edital_topicos e set resumo_id = m.resumo
  from melhor m where m.topico = e.id;
