-- Troca os tópicos de edital pelos editais OFICIAIS, e dá a eles um nível.
--
-- Até aqui `edital_topicos` tinha 326 linhas tiradas dos documentos de resumo
-- do autor — que são meio edital e meio conteúdo escrito, e por isso entraram
-- pela metade (ver o cabeçalho de `20260824120000`). Em 24/08 os três editais
-- oficiais foram baixados em `.docx`, e eles são a fonte de verdade:
--
--   * Edital 296/2026-Prograd/UFMS — PASSE, triênio 2026-2028, 1ª etapa
--   * Edital 297/2026-Prograd/UFMS — PASSE, triênio 2025-2027, 2ª etapa
--   * Programa do PAS/UEM 2026 — as três etapas
--
-- **Os dois editais do PASSE são de triênios diferentes**, e não é engano: o
-- aluno que faz a 1ª etapa em 2026 entra no triênio 2026-2028, e quem faz a 2ª
-- em 2026 entrou em 2025. `edital_topicos` não guarda triênio, e não precisa —
-- processo + etapa já identificam a prova. Mas quando o edital de 2027 chegar,
-- ele SUBSTITUI a 1ª etapa daqui, não soma.
--
-- 326 linhas saem, 1.114 entram.
--
-- ## O que ficou de fora, por decisão do autor
--
-- Os editais cobram **Língua Inglesa (88), Espanhola (66), Educação Física
-- (46) e Francesa (15)** — 215 tópicos cujas matérias não existem em
-- `materias`, e `edital_topicos.materia_slug` tem chave estrangeira. Perguntado
-- em 2026-08-24, o autor escolheu deixá-los de fora em vez de criar as quatro
-- matérias. **O `/edital` fica, portanto, menor que a prova real** — quem
-- comparar as duas coisas vai achar que falta, e falta mesmo.
--
-- A UFMS ainda parte a Matemática em três (Números e Álgebra, Geometria e
-- Medidas, Probabilidade e Estatística); as três caem em `matematica`, e a
-- ordem segue a do documento.
--
-- ## A coluna `nivel`, e por que não há numeração no texto
--
-- O programa do PAS/UEM é hierárquico: "Eletricidade e magnetismo" contém
-- "Eletrostática", que contém "Lei de Coulomb". Essa estrutura não está no
-- texto do parágrafo — no `.docx` ela é o `ilvl` do `numPr`, e o "2.1.3" que
-- se vê no PDF é desenhado pelo Word a partir de `numbering.xml`.
--
-- Reconstruir aquele número foi tentado e descartado: sem imitar
-- `startOverride` e `lvlRestart` inteiros, 44 dos 625 itens numerados saíam
-- errados — "1.1" onde o edital diz "3.1". Número errado é pior que nenhum,
-- porque é por ele que o aluno cita o item. Tirar do PDF também não serve: só
-- 76% das linhas têm par lá, porque o PDF quebra dois blocos de Física dentro
-- de tabelas.
--
-- Então o texto entra limpo e a hierarquia vira **`nivel`** (0 a 3), que vem
-- direto do `.docx` e não depende de contador nenhum. A coluna nasce
-- `default 0`, então nada que já lê a tabela quebra; quem quiser indentar o
-- `/edital` agora tem de onde. Os editais da UFMS são planos — tudo nível 0.
--
-- ## Os vínculos com resumo foram refeitos, não preservados
--
-- Os 25 `resumo_id` das linhas antigas não sobrevivem à troca: o texto mudou de
-- natureza. As linhas antigas eram títulos curtos ("Calor latente"), porque
-- vinham dos documentos do autor; as oficiais são frases inteiras do edital
-- ("Análise dos diferentes processos de propagação do calor"). Casar por
-- igualdade não acharia nada.
--
-- Então a religação é por CONTINÊNCIA: o tópico aponta para o resumo cujo
-- título aparece dentro do texto dele, na mesma matéria. Título com menos de 8
-- caracteres fica fora — "DIT", "Fatores" e "Sujeito" casariam com meio edital.
-- Havendo mais de um candidato, ganha o título mais longo, que é o mais
-- específico.
--
-- É uma heurística, e ela erra para menos: um resumo que cobre um tópico sem
-- repetir o próprio título no enunciado não é encontrado. Vincular à mão em
-- `/admin` continua valendo, e é o que o campo "Cobrado em" existe para fazer.
--
-- ## Como esta migration foi aplicada
--
-- Em blocos, e não de uma vez: são 110 KB de SQL, e a ferramenta que aplica
-- migrations neste ambiente não aceita tanto numa chamada só. A ordem foi a
-- daqui — coluna, delete, os cinco blocos de insert (um por processo e etapa)
-- e a religação. Conferido depois: 1.114 linhas, e o md5 do texto de todas
-- elas, na ordem de (processo, etapa, matéria, ordem), bate com o do arquivo
-- que as gerou.
--
-- O número da versão (`20260824211400`) é o que ficou registrado no histórico
-- do Supabase, e o arquivo foi renomeado para ele. A migration da Química, do
-- mesmo dia, precisou do mesmo acerto.
--
-- ## Como as linhas foram extraídas
--
-- `supabase/ferramentas/edital_para_migration.py`, versionado junto. O
-- cabeçalho dele conta as três armadilhas que os três documentos trouxeram —
-- entre elas um cabeçalho de matéria que é caixa de texto flutuante e some de
-- qualquer leitura por parágrafo, levando 21 tópicos de Química para dentro da
-- Física em silêncio.

